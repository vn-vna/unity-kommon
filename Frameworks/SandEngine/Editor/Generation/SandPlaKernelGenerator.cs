using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;

namespace Com.Scheherazade.Common.Frameworks.SandEngine.Editor
{
    /// <summary>
    /// Specializes the authoritative native physics into direct-array PLA kernels.
    /// Only storage types, job annotations and profiler scopes are changed.
    /// </summary>
    public sealed class SandPlaKernelGenerator : AssetPostprocessor
    {
        private const string Root = "Assets/Plugins/Scheherazade/Frameworks/SandEngine/Runtime/";
        private const string Output = Root + "SandPlaBackend/Generated/";
        private const string Marker = "// <auto-generated by SandPlaKernelGenerator>";
        private static bool _queued;

        private static readonly string[] Sources =
        {
            "SandAlgorithmCore.cs", "SandResolutionJobs.cs",
            "RegionalSandStepJob.cs", "SandBatchCollapse.cs"
        };

        [InitializeOnLoadMethod]
        private static void Initialize() => QueueRegeneration();

        private static void OnPostprocessAllAssets(string[] imported, string[] deleted,
            string[] moved, string[] movedFrom)
        {
            if (imported.Concat(moved).Any(path => Sources.Any(source => path == Root + source)))
                QueueRegeneration();
        }

        private static void QueueRegeneration()
        {
            if (_queued) return;
            _queued = true;
            EditorApplication.delayCall += () =>
            {
                _queued = false;
                if (EditorApplication.isCompiling) { QueueRegeneration(); return; }
                Regenerate();
            };
        }

        [MenuItem("Tools/SandSim/Sand PLA Backend/Regenerate Kernels")]
        public static void Regenerate()
        {
            foreach (var output in BuildOutputs())
            {
                if (File.Exists(output.Key))
                {
                    string existing = Normalize(File.ReadAllText(output.Key));
                    if (!existing.StartsWith(Marker, StringComparison.Ordinal))
                        throw new InvalidOperationException("Refusing to replace an unowned source: " + output.Key);
                    if (existing == output.Value) continue;
                }
                Directory.CreateDirectory(Path.GetDirectoryName(output.Key));
                File.WriteAllText(output.Key, output.Value, new UTF8Encoding(false));
                AssetDatabase.ImportAsset(output.Key);
            }
        }

        [MenuItem("Tools/SandSim/Sand PLA Backend/Validate Kernels")]
        public static void ValidateCurrent()
        {
            foreach (var output in BuildOutputs())
                if (!File.Exists(output.Key) || Normalize(File.ReadAllText(output.Key)) != output.Value)
                    throw new InvalidOperationException("Stale PLA kernel. Regenerate before testing/exporting: " + output.Key);
        }

        private static Dictionary<string, string> BuildOutputs()
        {
            return new Dictionary<string, string>
            {
                [Output + "SandPlaAlgorithmCore.g.cs"] = Generate("SandAlgorithmCore.cs", "SandAlgorithmCore", "SandPlaAlgorithmCore"),
                [Output + "SandPlaStep.g.cs"] = Generate("SandResolutionJobs.cs", "SingleThreadSandStepJob", "SandPlaStep"),
                [Output + "SandPlaRegionalStep.g.cs"] = Generate("RegionalSandStepJob.cs", "RegionalSandStepJob", "SandPlaRegionalStep"),
                [Output + "SandPlaBatchCollapse.g.cs"] = Generate("SandBatchCollapse.cs", "SandBatchCollapse", "SandPlaBatchCollapse")
            };
        }

        private static string Generate(string source, string originalType, string outputType)
        {
            string original = Normalize(File.ReadAllText(Root + source));
            string native = SelectNativeBranches(original);
            string body = ExtractType(native, originalType);
            body = Regex.Replace(body, @"\bNativeArray<int>|\bSandIntBuffer\b", "int[]");
            body = Regex.Replace(body, @"\bNativeArray<byte>|\bSandByteBuffer\b", "byte[]");
            body = Regex.Replace(body, @"\[(ReadOnly|WriteOnly|NativeDisableParallelForRestriction|BurstCompile)\]\s*", "");
            body = Regex.Replace(body, @"\s*:\s*IJob\b", "");
            body = Regex.Replace(body, @"\b" + originalType + @"\b", outputType);
            body = Regex.Replace(body, @"\bSandAlgorithmCore\b", "SandPlaAlgorithmCore");
            body = Regex.Replace(body, @"^\s*private static readonly ProfilerMarker Marker\s*=\s*\n\s*new ProfilerMarker\([^\n]+\);\n", "\n", RegexOptions.Multiline);
            body = Regex.Replace(body, @"^\s*using \(Marker.Auto\(\)\)\s*\n", "\n", RegexOptions.Multiline);
            if (body.Contains("NativeArray<") || body.Contains("ProfilerMarker") || body.Contains("#if"))
                throw new InvalidOperationException("Unrecognized native dependency in " + source);

            string hash;
            using (var sha = SHA256.Create())
                hash = BitConverter.ToString(sha.ComputeHash(Encoding.UTF8.GetBytes(original))).Replace("-", "").ToLowerInvariant();
            return Marker + "\n// Source: " + Root + source + "\n// SHA-256: " + hash
                + "\n// Edit the native source; generated PLA kernels must never be edited by hand.\n"
                + (originalType == "SandBatchCollapse" ? "#if PLA_CREATIVE_BUILD\n" : "#if PLA_CREATIVE_BUILD || UNITY_EDITOR\n")
                + "using System;\nusing System.Collections.Generic;\n"
                + "using Com.Scheherazade.Common.Frameworks.GridSystem;\nusing UnityEngine;\n"
                + "#if PLA_CREATIVE_BUILD\nusing PortableMath = Com.Scheherazade.Common.Compatibility.CreativeMath;\n"
                + "using PortableArray = Com.Scheherazade.Common.Compatibility.CreativeArray;\n#else\n"
                + "using PortableMath = System.Math;\nusing PortableArray = System.Array;\n#endif\n\n"
                + "namespace Com.Scheherazade.Common.Frameworks.SandEngine.Pla\n{\n" + body + "\n}\n#endif\n";
        }

        private static string SelectNativeBranches(string source)
        {
            var result = new StringBuilder();
            var stack = new Stack<(bool parent, bool condition)>();
            bool enabled = true;
            foreach (string line in source.Split('\n'))
            {
                string directive = line.Trim();
                if (directive.StartsWith("#if ", StringComparison.Ordinal))
                {
                    string condition = directive.Substring(4).Trim();
                    if (condition != "PLA_CREATIVE_BUILD" && condition != "!PLA_CREATIVE_BUILD")
                        throw new InvalidOperationException("Unexpected solver directive: " + directive);
                    bool selected = condition == "!PLA_CREATIVE_BUILD";
                    stack.Push((enabled, selected));
                    enabled &= selected;
                }
                else if (directive == "#else")
                {
                    var state = stack.Peek();
                    enabled = state.parent && !state.condition;
                }
                else if (directive == "#endif") enabled = stack.Pop().parent;
                else if (enabled) result.AppendLine(line);
            }
            if (stack.Count != 0) throw new InvalidOperationException("Unbalanced solver directives.");
            return Normalize(result.ToString());
        }

        private static string ExtractType(string source, string name)
        {
            var match = Regex.Match(source, @"(?m)^    (?:internal|public) (?:(?:static|sealed|readonly) )?(?:class|struct) " + name + @"\b");
            if (!match.Success) throw new InvalidOperationException("Missing solver type: " + name);
            int open = source.IndexOf('{', match.Index);
            int depth = 0;
            bool lineComment = false, blockComment = false;
            char quote = '\0';
            for (int index = open; index < source.Length; index++)
            {
                char c = source[index];
                char next = index + 1 < source.Length ? source[index + 1] : '\0';
                if (lineComment) { if (c == '\n') lineComment = false; continue; }
                if (blockComment) { if (c == '*' && next == '/') { blockComment = false; index++; } continue; }
                if (quote != '\0') { if (c == '\\') index++; else if (c == quote) quote = '\0'; continue; }
                if (c == '/' && next == '/') { lineComment = true; index++; continue; }
                if (c == '/' && next == '*') { blockComment = true; index++; continue; }
                if (c == '"' || c == '\'') { quote = c; continue; }
                if (c == '{') depth++;
                else if (c == '}' && --depth == 0) return source.Substring(match.Index, index - match.Index + 1);
            }
            throw new InvalidOperationException("Unbalanced solver type: " + name);
        }

        private static string Normalize(string value) => value.Replace("\r\n", "\n").TrimStart('\uFEFF');
    }
}
